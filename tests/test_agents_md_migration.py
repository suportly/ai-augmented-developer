_FENCED_FAKE_AUTOSTACK_SAMPLE = (
    "```markdown\n"
    "<!-- aiadev:auto-stack:start -->\n"
    "## Detected stack\n"
    "<!-- aiadev:auto-stack:end -->\n"
    "```"
)

_FENCED_FAKE_MIGRATED_SAMPLE = (
    "```markdown\n"
    "<!-- aiadev:migrated-legacy:start -->\n"
    "example payload shown in docs\n"
    "<!-- aiadev:migrated-legacy:end -->\n"
    "```"
)


class TestFenceAwareMigration:
    """Adversarial inputs: marker syntax quoted inside fenced code samples.

    The marker strings appear verbatim in the framework's own docs, so a
    legacy CLAUDE.md whose manual prose *documents* the managed-block
    syntax inside a fenced code sample is realistic. Neither the
    migration's managed-block stripping nor the later re-extraction of
    the migrated-legacy payload may treat those fenced samples as real
    block boundaries.
    """

    def test_fenced_fake_autostack_markers_survive_migration_intact(
        self, isolated_framework, tmp_path, monkeypatch
    ):
        monkeypatch.setenv("AIADEV_ROOT", str(isolated_framework))
        project = tmp_path / "claude-fenced-autostack"
        project.mkdir()
        result = _install(project, platform="claude-code")
        assert result.exit_code == 0, result.output

        legacy_text = (
            "# LegacyDemo\n\n"
            "## How our managed block works\n\n"
            "The sync tool maintains a block that looks like this:\n\n"
            f"{_FENCED_FAKE_AUTOSTACK_SAMPLE}\n\n"
            "- Real convention: we always squash-merge.\n\n"
            + _LEGACY_STACK_BLOCK
        )
        (project / "CLAUDE.md").write_text(legacy_text, encoding="utf-8")
        _mark_wrapper_as_tracked(project, "CLAUDE.md")

        sync_result = _sync(project, platform="claude-code")
        assert sync_result.exit_code == 0, sync_result.output

        agents_text = (project / "AGENTS.md").read_text(encoding="utf-8")
        # The fenced sample — fake markers and all — survives byte-intact
        # inside the migrated-legacy block; only the REAL managed block
        # was stripped from the migrated content.
        assert _FENCED_FAKE_AUTOSTACK_SAMPLE in agents_text
        assert "How our managed block works" in agents_text
        assert "squash-merge" in agents_text
        # The legacy file's REAL (stale, 2020-stamped) auto-stack block
        # was stripped rather than migrated: only the freshly regenerated
        # block's timestamp may appear.
        assert "2020-01-01T00:00:00Z" not in agents_text

    def test_fenced_fake_migrated_legacy_markers_round_trip_byte_stable(
        self, isolated_framework, tmp_path, monkeypatch
    ):
        monkeypatch.setenv("AIADEV_ROOT", str(isolated_framework))
        project = tmp_path / "claude-fenced-migrated"
        project.mkdir()
        result = _install(project, platform="claude-code")
        assert result.exit_code == 0, result.output

        legacy_text = (
            "# LegacyDemo\n\n"
            "Pasted example of the migration block syntax:\n\n"
            f"{_FENCED_FAKE_MIGRATED_SAMPLE}\n\n"
            "Tail content after the fence that must never be truncated away.\n\n"
            + _LEGACY_STACK_BLOCK
        )
        (project / "CLAUDE.md").write_text(legacy_text, encoding="utf-8")
        _mark_wrapper_as_tracked(project, "CLAUDE.md")

        first = _sync(project, platform="claude-code")
        assert first.exit_code == 0, first.output

        agents_after_first = (project / "AGENTS.md").read_text(encoding="utf-8")
        assert _FENCED_FAKE_MIGRATED_SAMPLE in agents_after_first
        assert "Tail content after the fence" in agents_after_first

        # Second sync must re-extract the FULL payload (no truncation at
        # the fenced fake `:end` marker) and re-apply it byte-identically.
        second = _sync(project, platform="claude-code")
        assert second.exit_code == 0, second.output
        assert "conflict" not in second.output.lower()

        agents_after_second = (project / "AGENTS.md").read_text(encoding="utf-8")
        assert agents_after_second == agents_after_first
        assert _FENCED_FAKE_MIGRATED_SAMPLE in agents_after_second
        assert "Tail content after the fence" in agents_after_second


class TestAlreadyWrapperUntouched:
    def test_fresh_install_wrapper_is_not_migrated(
        self, isolated_framework, tmp_path, monkeypatch
    ):
        monkeypatch.setenv("AIADEV_ROOT", str(isolated_framework))
        project = tmp_path / "claude-fresh"
        project.mkdir()
        result = _install(project, platform="claude-code")
        assert result.exit_code == 0, result.output

        claude_before = (project / "CLAUDE.md").read_bytes()

        sync_result = _sync(project, platform="claude-code")
        assert sync_result.exit_code == 0, sync_result.output

        assert not (project / "CLAUDE.md.bak").exists()
        assert (project / "CLAUDE.md").read_bytes() == claude_before
